/**
 * Mock 数据的「进程内固定当前时间」。
 *
 * 消费排行榜的周期榜（今日 / 昨日 / 本周 / 本月 / 上月）必须有订单落在对应区间里才看得见，
 * 而那些订单的时间**只能相对当前时间**构造：写死 2026-09-13 这种绝对日期，
 * 过几天「今日」就永远是空的，验收时看到的是一张空榜而不是一个坏掉的页签。
 *
 * 相对时间带来一个新问题：如果每次查询都按「此刻」重算一遍，同一个进程里翻页前后
 * 订单的完成时间都在变，榜单会自己漂移（第一页与第二页对不上，甚至名次来回换）。
 * 因此这里把「基准时间」在**进程内固定一次**：
 *
 * - 同一进程内多次读取得到同一个时间戳 → 同一份 Mock 数据，榜单稳定、可复现；
 * - 重启服务后重新取一次 → 第二天再打开，数据自然落到新的「今日」；
 * - 需要确定性的测试可以显式传入自己的 `now` 给 `buildRankingPeriodOrders`，
 *   不依赖真实执行日期。
 *
 * ⚠️ 与 `lib/mocks` 一同在接入真实后端后移除。
 */

let seedNow: Date | null = null;

/** 进程内固定的基准时间（首次调用时确定）。返回副本，调用方改不到内部状态。 */
export function getMockSeedNow(): Date {
  if (!seedNow) seedNow = new Date();
  return new Date(seedNow.getTime());
}

/** 清掉固定值，下次调用重新取当前时间。仅供测试使用（重放「服务重启」）。 */
export function resetMockSeedNow(): void {
  seedNow = null;
}
