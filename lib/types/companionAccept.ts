/**
 * 接单事件 `CompanionAcceptEvent`（P1-5）——**只增不改**的历史。
 *
 * ## 它为什么必须存在（不是「顺手加一张表」）
 *
 * 派单记录（`DispatchRecord`）上的「谁接了」是一个**当前状态**字段：它只有**一个**
 * `acceptedByCompanionId`，而换人（P0-11 客服改派）会**复用同一条派单记录**并覆盖它
 * （`lib/data/mockDispatchRepository.ts` 的 `applyDispatchToPublic()` 显式清空、
 * 之后新的接单再写一次），再加上 `dispatchIdByOrder` 保证**一单只有一行派单记录**，
 * 于是「这一单上先后有几个人接过」在现模型里**根本读不出来**。
 *
 * 而产品裁定（`rounds/P1-5/02-decisions.md` §3 / §8）要求接单榜统计的是
 * **成功的 `acceptDispatch` 事件次数**，并给定算例：
 *
 * ```
 * A → B → A   ⇒   A 接单 2 次、B 接单 1 次
 * ```
 *
 * 并明确「后续取消 / 换人 / 退款 / 未完成**不回写、删除**之前真实发生过的成功接单事件」。
 * 一条只增不改的历史是这句话**唯一**的落点。这与履约退出历史
 * （`CompanionReleaseRecord`，P0-6）是**同一个理由的两处应用**，不是「第二套追溯表」：
 * 退出历史回答「谁**走**了」（由退出动作写），接单事件回答「谁**来**了」（由接单动作写），
 * 两者都是**动作**留下的历史，都不能从当前状态字段反推出来。
 *
 * ⚠️ **两者的界分要守住**：接单事件**不记**「为什么接、接之前发生了什么」，
 * 退出历史**不记**「谁接过」。一件事仍然只有一个出处。
 *
 * ## 为什么只有 5 个字段
 *
 * 它要回答的问题只有一个：「**在这个周期里，这位打手成功接过几次**」。
 * 因此只记：谁、哪一单、哪一条派单、什么时候。**不记**金额（接单不产生钱）、
 * **不记**订单状态快照（状态是**现在**的事实，写进历史就是伪造历史）、
 * **不记**「第几次接单」（那是查询时按时间数出来的，不是存下来的——
 * 存下来就会出现两条记录对同一个「第几次」给出不同答案）。
 *
 * ⚠️ 与 `CompanionReleaseRecord` 一样：**页面与接口不直接返回本类型**，
 * 它是接单榜的**输入**，不是可以对外展示的东西（对外只给聚合后的名次与指标值）。
 */

/**
 * 一条接单事件。
 *
 * ⚠️ **没有 `id` 之外的业务键**：`(dispatchId, companionId, acceptedAt)` 三元组
 * 在真实实现里是「同一次接单不会写两条」的判据，但它是**推导**出来的，不是字段本身——
 * 记录里不重复表达一次。
 */
export type CompanionAcceptEvent = {
  id: string;
  /** 这次接单发生在**哪一条派单**上。换人会复用同一条派单，因此它**不是**唯一键 */
  dispatchId: string;
  /** 被接的是哪一单 */
  orderId: string;
  /** **实际接单**的这位打手。⚠️ 与订单当前的 `actualCompanionId` 可以不同（换人之后） */
  companionId: string;
  /** 接单成功的那一刻 */
  acceptedAt: string;
};

/**
 * 接单事件在**没有历史记录**时仍可考据的那一次。
 *
 * ## 为什么需要「派生」
 *
 * 本事件表建仓时是**空的**（不伪造历史，理由同 `mockCompanionReleaseRepository`）。
 * 但 `dispatchSeed` 里那些 `state === "accepted"` 的派单记录**本身**就是一段真实的
 * 接单事实：它的 `acceptedByCompanionId` / `acceptedAt` 与订单的
 * `acceptedAt` 同源（见 `lib/mocks/fixtures/dispatchSeed.ts` 的说明）。
 * 读取侧因此对这**唯一一次**仍可考据的接单做**派生**，让榜单在一份干净的预置数据上
 * 不是空的——这与「编造一段从未发生过的历史」是两件事：派单记录上白纸黑字写着
 * 有人接了、什么时候接的，派生只是把它读出来。
 *
 * ## ⚠️ 派生的边界（必须如实告知，不要当成完整历史）
 *
 * 派生**只补「最后一次」**。因为派单记录只会保留当前那一位接单人，所以对
 * **历史上真的发生过 A → B → A 的存量单**，读取侧只能看到最后一次的 A，
 * **中间那次 B 与第一次的 A 已经不存在于任何地方**。
 *
 * → 结论：**在存量数据上，接单榜的数字是下界**（只少不多）。
 * 这是一条**数据可获得性**的限制，不是口径上的妥协；换成真实数据库后，
 * 只要事件表从第一天就在，就不会再有这个问题（`database-schema.md` 的迁移约束）。
 *
 * ## ⚠️ 只派生**打手自己接的**那一种（P1-5 §九-F 产品裁定）
 *
 * 判据是 `DispatchRecord.acceptedVia`（`"companion"` / `"staff"` / `null`）：
 * **只有 `"companion"` 派生**。客服直换 / 直接指定（`"staff"`）**不是**打手的主动接单行为，
 * 不得算进接单榜；`null`（认不出来源）**也不派生**——**宁可低，不猜**。
 *
 * 裁定原文：「`deriveLegacyAcceptEvents()` 不得把能够识别为 Staff direct replacement /
 * Staff direct assignment 的历史绑定记录推导成 `CompanionAcceptEvent`。如果历史数据
 * 无法区分：不得凭空补接单事件。宁可继续保持『存量接单榜是历史下界』。**不要为了让
 * 历史数字好看而伪造主动接单行为。**」
 *
 * → 因此**存量榜比「只补最后一次」还要更低一档**：可识别为客服直换的、以及
 * 认不出来源的，一条都不补。**这是有意选的保守方向**，不是缺陷。
 * ⚠️ 与之相对，**「订单进入 `accepted`」与「产生一次接单事件」是两个概念**——
 * 直换照样让订单进 `accepted`，只是不产生事件（细节见 `lib/types/dispatch.ts` 的
 * `DispatchAcceptSource`）。
 */
export type DerivedAcceptEvent = {
  /** 与真实记录同一个形状，但 id 由派单记录派生（不占用事件表的 id 空间） */
  dispatchId: string;
  orderId: string;
  companionId: string;
  acceptedAt: string;
};
