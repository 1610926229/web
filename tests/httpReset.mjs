/**
 * 把**服务进程**的 Mock 存储丢回预置数据——HTTP 用例的隔离基线。
 *
 * ## 它解决什么
 *
 * `node --test` 让每个测试文件跑在**自己的子进程**里，所以进程内的用例之间天然隔离：
 * `resetMockStore()` 换掉的是本进程的存储，一个文件碰不到另一个。
 *
 * 但带 `APP_BASE_URL` 的那批用例打的是**另一个进程**——`next start` 起的服务。
 * 测试进程里的 `resetMockStore()` 够不着它，而且**没有**任何 HTTP 接口能重置它。
 * 于是服务端那份存储**只增不减**：下单、退款、建券、发券……跑得越多离预置状态越远。
 *
 * 旧办法是把这条约束**写进文件头靠人遵守**（「要跑门禁请重启服务」），
 * 没有任何东西强制它。后果是**偶发**的：前几次跑绿，第十几次开始某个用例
 * 读到的是前面几十个文件攒下来的状态，失败既不像回归、又复现不了。
 *
 * 现在每个 HTTP 测试文件在**发起第一个请求之前**调一次这个函数，
 * 服务端把整族存储丢回预置。于是每个文件都从「刚重启的服务」出发——
 * 那正是文件头一直在要求的条件，只是从「请人工遵守」变成了「自动保证」。
 *
 * ## 为什么必须在**文件开头**调，而不是每个用例之前
 *
 * 重置是**全局**的：它清的是整个服务端存储，不是「我这个文件的那一份」。
 * 因此两个 HTTP 文件**同时**跑会互相清掉对方的中间状态。
 * 配套约束是 `package.json` 里 `--test-concurrency=1`：HTTP 文件串行跑，
 * 重置与被重置之间不会插进第三个文件。两者是一套的，**不能只留一个**。
 *
 * ## 为什么它**失败要抛错**，而不是静默跳过
 *
 * 「重置不了」和「重置成功」在用例看来都是「继续跑」。如果静默放过，
 * 隔离保证就悄悄失效了——那正是旧机制的老毛病换了个地方重演。
 * 因此拿不到 200 就直接抛：宁可在第一个文件上响亮地失败，也不要一个
 * 归因不明的偶发红。
 *
 * 服务端未开启 `ENABLE_MOCK_DEBUG` 时 `/api/debug/reset` 返回 404（接口不存在），
 * 这里就会抛。这是**有意的**：跑 HTTP 用例的服务端必须开着该开关，
 * 否则这批用例本来就退化成「读到什么都算」。
 *
 * ## 不设 `APP_BASE_URL` 时
 *
 * 直接返回 `null`，不发任何请求。`pnpm test` 不开服务时因此完全不受影响，
 * 与那 177 条 HTTP 用例一起走「跳过」这条路。
 */
export async function resetServerStores() {
  const base = process.env.APP_BASE_URL;
  if (!base) return null;

  const response = await fetch(new URL("/api/debug/reset", base), {
    method: "POST",
  });

  if (!response.ok) {
    throw new Error(
      `重置服务端 Mock 存储失败：POST /api/debug/reset → HTTP ${response.status}。` +
        `跑 HTTP 用例的服务端需要 ENABLE_MOCK_DEBUG=true（见 .env.local）。` +
        `不重置就继续跑，本文件的断言会读到前面用例攒下来的状态，失败将无法归因——因此这里直接失败。`,
    );
  }

  // 读干响应体：不读会让这条连接悬着，而这是唯一一处「每个文件都必然发生」的请求，
  // 不值得为它留一个不确定的连接状态。
  const payload = await response.json();
  return payload?.data?.reset ?? null;
}
